/** Exercises actual Accent-generated bytecode through Spring contexts, MVC, and JDBC. */
class AccentSpringEndToEndTest {
    @TempDir static Path tempDir;
    private static URLClassLoader loader;
    private static Class<?> endpoint;
    private static Class<?> qualified;

    @BeforeAll
    static void compileAccentWithoutJavaRecompilation() throws Exception {
        Path sources = Files.createDirectory(tempDir.resolve("src"));
        Files.writeString(sources.resolve("Endpoint.accent"), """
                package integrationfixture;
                import org.springframework.web.bind.annotation.*;
                import accent.html.Html;
                @RestController
                public class Endpoint {
                    @GetMapping("/query")
                    public String query(@RequestParam("q") String actual) { return actual; }
                    @GetMapping("/path/{id}")
                    public String path(@PathVariable("id") String actual) { return actual; }
                    @PostMapping("/body")
                    public String body(@RequestBody String payload) { return payload; }
                    @GetMapping("/implicit")
                    public String implicit(String name) { return name; }
                    @GetMapping("/html")
                    public Html html() { return (<p>Hello HTML</p>); }
                    @GetMapping("/component")
                    public Welcome component() { return new Welcome("Lem"); }
                    @GetMapping("/json")
                    public Payload json() { return new Payload("hello"); }
                    @GetMapping("/null-html")
                    public Html empty() { return null; }
                }
                """);
        Files.writeString(sources.resolve("Welcome.accent"), """
                package integrationfixture;
                import accent.html.Component;
                import accent.html.Html;
                public record Welcome(String name) implements Component {
                    public Html render() { return (<p>{this.name}</p>); }
                }
                """);
        Files.writeString(sources.resolve("Payload.accent"), "package integrationfixture; public record Payload(String message) {}");
        Files.writeString(sources.resolve("Qualified.accent"), """
                package integrationfixture;
                import org.springframework.beans.factory.annotation.Qualifier;
                public class Qualified {
                    private final String value;
                    public Qualified(@Qualifier("right") String value) { this.value = value; }
                    public String value() { return this.value; }
                }
                """);
        Files.writeString(sources.resolve("QualifiedRecord.accent"), """
                package integrationfixture;
                import org.springframework.beans.factory.annotation.Qualifier;
                public record QualifiedRecord(@Qualifier("right") String value) {}
                """);
        Files.writeString(sources.resolve("QualifiedModel.accent"), """
                package integrationfixture;
                import org.springframework.beans.factory.annotation.Qualifier;
                public model QualifiedModel(@Qualifier("right") String value) {}
                """);
        Path output = tempDir.resolve("classes");
        List<String> classpath = Arrays.asList(System.getProperty("java.class.path").split(java.io.File.pathSeparator));
        var result = new AccentCompiler().compile(List.of(sources), output, classpath, tempDir.resolve("java"), true);
        assertTrue(result.successful(), () -> result.diagnostics().toString());
        loader = new URLClassLoader(new java.net.URL[]{output.toUri().toURL()});
        endpoint = loader.loadClass("integrationfixture.Endpoint");
        qualified = loader.loadClass("integrationfixture.Qualified");
    }

    @AfterAll
    static void closeLoader() throws Exception { if (loader != null) loader.close(); }

    @Configuration(proxyBeanMethods = false)
    @EnableWebMvc
    static class MvcConfiguration {}

    @Configuration(proxyBeanMethods = false)
    @EnableAutoConfiguration
    static class BootConfiguration {}

    private WebApplicationContextRunner webRunner() {
        return new WebApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(AccentHtmlAutoConfiguration.class))
                .withUserConfiguration(MvcConfiguration.class)
                .withInitializer(context -> ((BeanDefinitionRegistry) context.getBeanFactory())
                        .registerBeanDefinition("accentEndpoint", new RootBeanDefinition(endpoint)));
    }

    @Test
    void preservesParameterAnnotationsInCompiledBytecode() throws Exception {
        var annotation = endpoint.getMethod("query", String.class).getParameters()[0].getAnnotation(RequestParam.class);
        assertNotNull(annotation);
        assertEquals("q", annotation.value());
    }

    @Test
    void preservesParameterNamesInDirectCompilerOutput() throws Exception {
        var parameter = endpoint.getMethod("implicit", String.class).getParameters()[0];
        assertTrue(parameter.isNamePresent());
        assertEquals("name", parameter.getName());
    }

    @Test
    void springBindsExplicitQueryPathAndBodyAnnotations() {
        webRunner().run(context -> {
            assertThat(context).hasNotFailed();
            MockMvc mvc = MockMvcBuilders.webAppContextSetup(context).build();
            mvc.perform(get("/query").param("q", "Lem")).andExpect(status().isOk()).andExpect(content().string("Lem"));
            mvc.perform(get("/path/Ana")).andExpect(status().isOk()).andExpect(content().string("Ana"));
            mvc.perform(post("/body").contentType("text/plain").content("request body"))
                    .andExpect(status().isOk()).andExpect(content().string("request body"));
        });
    }

    @Test
    void springBindsImplicitQueryParameterUsingCompilerMetadata() {
        webRunner().run(context -> {
            assertThat(context).hasNotFailed();
            MockMvcBuilders.webAppContextSetup(context).build().perform(get("/implicit").param("name", "Lem"))
                    .andExpect(status().isOk()).andExpect(content().string("Lem"));
        });
    }

    @Test
    void constructorQualifierResolvesAmbiguousBeans() {
        new ApplicationContextRunner().withBean("left", String.class, () -> "wrong")
                .withBean("right", String.class, () -> "selected")
                .withInitializer(context -> {
                    var definition = new RootBeanDefinition(qualified);
                    definition.setAutowireMode(AutowireCapableBeanFactory.AUTOWIRE_CONSTRUCTOR);
                    ((BeanDefinitionRegistry) context.getBeanFactory()).registerBeanDefinition("qualified", definition);
                }).run(context -> {
                    assertThat(context).hasNotFailed();
                    assertEquals("selected", qualified.getMethod("value").invoke(context.getBean("qualified")));
                });
    }

    @Test
    void recordAndModelConstructorAnnotationsSupportSpringInjection() throws Exception {
        for (String name : List.of("QualifiedRecord", "QualifiedModel")) {
            Class<?> type = loader.loadClass("integrationfixture." + name);
            new ApplicationContextRunner().withBean("left", String.class, () -> "wrong")
                    .withBean("right", String.class, () -> "selected")
                    .withInitializer(context -> {
                        var definition = new RootBeanDefinition(type);
                        definition.setAutowireMode(AutowireCapableBeanFactory.AUTOWIRE_CONSTRUCTOR);
                        ((BeanDefinitionRegistry) context.getBeanFactory()).registerBeanDefinition("qualified", definition);
                    }).run(context -> {
                        assertThat(context).hasNotFailed();
                        assertEquals("selected", type.getMethod("value").invoke(context.getBean("qualified")));
                    });
        }
    }

    @Test
    void bootAutoDiscoveryInstallsHtmlHandlerForRestControllers() {
        new WebApplicationContextRunner().withUserConfiguration(BootConfiguration.class)
                .withInitializer(context -> ((BeanDefinitionRegistry) context.getBeanFactory())
                        .registerBeanDefinition("accentEndpoint", new RootBeanDefinition(endpoint)))
                .run(context -> {
                    assertThat(context).hasNotFailed();
                    MockMvcBuilders.webAppContextSetup(context).build().perform(get("/html"))
                            .andExpect(status().isOk()).andExpect(content().string("<p>Hello HTML</p>"))
                            .andExpect(content().contentType("text/html;charset=UTF-8"));
                });
    }

    @Test
    void htmlAndComponentFromRestControllerRenderAsHtmlWithoutChangingJson() {
        webRunner().run(context -> {
            assertThat(context).hasNotFailed();
            MockMvc mvc = MockMvcBuilders.webAppContextSetup(context).build();
            mvc.perform(get("/html").accept("text/html")).andExpect(status().isOk())
                    .andExpect(content().contentType("text/html;charset=UTF-8")).andExpect(content().string("<p>Hello HTML</p>"));
            mvc.perform(get("/component")).andExpect(status().isOk())
                    .andExpect(content().contentType("text/html;charset=UTF-8")).andExpect(content().string("<p>Lem</p>"));
            mvc.perform(get("/json").accept("application/json")).andExpect(status().isOk())
                    .andExpect(content().json("{\"message\":\"hello\"}"));
            mvc.perform(get("/null-html")).andExpect(status().isOk()).andExpect(content().string(""));
        });
    }

    @Test
    void starterStartsWithoutMvcInNonWebApplication() {
        new ApplicationContextRunner().withUserConfiguration(BootConfiguration.class).run(context -> {
            assertThat(context).hasNotFailed();
            assertThat(context).doesNotHaveBean(AccentFileRouter.class);
        });
    }

    @Test
    void starterStartsWhenMvcClassesAreUnavailable() {
        new ApplicationContextRunner().withClassLoader(new FilteredClassLoader("org.springframework.web.servlet"))
                .withUserConfiguration(BootConfiguration.class).run(context -> {
                    assertThat(context).hasNotFailed();
                    assertThat(context).doesNotHaveBean(AccentFileRouter.class);
                });
    }

    @Test
    void jdbcIntegrationRemainsOptionalForNonDatabaseApplications() {
        new ApplicationContextRunner().withClassLoader(new FilteredClassLoader("org.springframework.jdbc"))
                .withUserConfiguration(BootConfiguration.class).run(context -> {
                    assertThat(context).hasNotFailed();
                    assertFalse(context.containsBean("accentSqlDataSourceInitializer"));
                });
    }

    private ApplicationContextRunner sqlRunner(DataSource dataSource) {
        return new ApplicationContextRunner().withUserConfiguration(BootConfiguration.class)
                // Before the fix, permit HTML auto-configuration to start so transaction behavior is tested independently.
                .withBean(RequestMappingHandlerMapping.class, RequestMappingHandlerMapping::new)
                .withBean(DataSource.class, () -> dataSource);
    }

    @Test
    void accentSqlParticipatesInSpringRollbackAndCommit() {
        var dataSource = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        sqlRunner(dataSource).run(context -> {
            assertThat(context).hasNotFailed();
            try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
                statement.execute("CREATE TABLE item(name VARCHAR(100))");
            }
            var transactions = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
            transactions.executeWithoutResult(status -> {
                Sql.execute("INSERT INTO item(name) VALUES (?)", List.of("rollback"), Void.class);
                status.setRollbackOnly();
            });
            assertEquals(0, countRows(dataSource));
            assertThrows(IllegalStateException.class, () -> transactions.executeWithoutResult(status -> {
                Sql.execute("INSERT INTO item(name) VALUES (?)", List.of("failed request"), Void.class);
                throw new IllegalStateException("Simulated service failure");
            }));
            assertEquals(0, countRows(dataSource));
            transactions.executeWithoutResult(status -> {
                Sql.execute("INSERT INTO item(name) VALUES (?)", List.of("first"), Void.class);
                Sql.execute("INSERT INTO item(name) VALUES (?)", List.of("second"), Void.class);
            });
            assertEquals(2, countRows(dataSource));
            Sql.execute("INSERT INTO item(name) VALUES (?)", List.of("outside transaction"), Void.class);
            assertEquals(3, countRows(dataSource));
        });
    }

    private static int countRows(DataSource dataSource) throws Exception {
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement();
                var result = statement.executeQuery("SELECT COUNT(*) FROM item")) {
            result.next(); return result.getInt(1);
        }
    }
}
